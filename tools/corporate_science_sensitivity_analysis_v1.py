r_lookup = {(a, int(y)): float(w) for a, y, w in r.itertuples(index=False, name=None)}

def pretrend_slope(row):
    a = r_lookup.get((str(row.company_id), int(row.entry_year) - 3), 0.0)
    b = r_lookup.get((str(row.company_id), int(row.entry_year) - 1), 0.0)
    return (math.log1p(b) - math.log1p(a)) / 2.0

ADJ = [
    "log_pre3_research_output",
    "log_pre3_research_citations",
    "pretrend_slope",
    "pre3_collab_countries",
    "pre3_network_hhi_complement",
    "pre3_network_entropy",
    "log_pre3_collab_works",
    "pre3_network_observed",
]
OUTCOME_COMMON = "z_log_pre3_research_output + z_log_pre3_research_citations + z_pretrend_slope + z_pre3_network_entropy + z_log_pre3_collab_works"
OUTCOME_COMMON_NO_ENTROPY = "z_log_pre3_research_output + z_log_pre3_research_citations + z_pretrend_slope + z_log_pre3_collab_works"
FE3 = "topic_id + company_id + entry_year"
FE_H4 = "topic_id + company_id"

def ess(w):
    w = np.asarray(w, float)
    return float((w.sum() ** 2) / np.sum(w ** 2)) if len(w) and np.sum(w ** 2) > 0 else 0.0

def wmean(x, w):
    x = np.asarray(x, float); w = np.asarray(w, float)
    return float(np.sum(w * x) / np.sum(w))

def smd(a, b, wa=None, wb=None):
    a = np.asarray(a, float); b = np.asarray(b, float)
    if wa is None:
        ma, mb = float(np.mean(a)), float(np.mean(b))
        va, vb = float(np.var(a, ddof=1)), float(np.var(b, ddof=1))
    else:
        wa = np.asarray(wa, float); wb = np.asarray(wb, float)
        ma, mb = wmean(a, wa), wmean(b, wb)
        va = float(np.sum(wa * (a - ma) ** 2) / np.sum(wa))
        vb = float(np.sum(wb * (b - mb) ** 2) / np.sum(wb))
    den = math.sqrt(max((va + vb) / 2.0, 0.0))
    return 0.0 if den == 0 else float((ma - mb) / den)

def prepare_df(tbl: str) -> tuple[pd.DataFrame, dict]:
    # Add +1..+2 output from the same company-topic mart; +3/+5 outcomes are already generated by frozen code.
    q = f"""
    SELECT p.*,
           COALESCE(SUM(CASE WHEN tt.yr BETWEEN p.entry_year+1 AND p.entry_year+2
                             THEN tt.work_count ELSE 0 END),0) AS post2_topic_output
    FROM {tbl} p
    LEFT JOIN t tt
      ON tt.company_id=p.company_id AND tt.topic_id=p.topic_id
     AND tt.yr BETWEEN p.entry_year+1 AND p.entry_year+2
    GROUP BY ALL
    """
    d = con.execute(q).df()
    d["company_id"] = d["company_id"].astype(str)
    d["topic_id"] = d["topic_id"].astype(str)
    d["entry_year"] = d["entry_year"].astype(int)
    d["sic2"] = d["sic"].astype(str).str.extract(r"(\d{2})", expand=False).fillna("UNK")
    d["pretrend_slope"] = d.apply(pretrend_slope, axis=1)
    d["log_pre3_research_output"] = np.log1p(pd.to_numeric(d["pre3_research_output"], errors="coerce").fillna(0))
    d["log_pre3_research_citations"] = np.log1p(pd.to_numeric(d["pre3_research_citations"], errors="coerce").fillna(0))
    d["log_pre3_collab_works"] = np.log1p(pd.to_numeric(d["pre3_collab_works"], errors="coerce").fillna(0))
    d["y_h1_2"] = np.log1p(pd.to_numeric(d["post2_topic_output"], errors="coerce").fillna(0))
    d["y_h1_3"] = np.log1p(pd.to_numeric(d["post3_topic_output"], errors="coerce").fillna(0))
    d["y_h1_5"] = np.log1p(pd.to_numeric(d["post5_topic_output"], errors="coerce"))
    d["y_h2_3"] = pd.to_numeric(d["active_at_plus3"], errors="coerce")
    d["y_h2_5"] = pd.to_numeric(d["active_at_plus5"], errors="coerce")
    d["y_h3_3"] = np.log1p(pd.to_numeric(d["post3_field_year_norm_citation_ratio"], errors="coerce"))

    for c in ADJ:
        x = pd.to_numeric(d[c], errors="coerce")
        med = float(x.median()) if x.notna().any() else 0.0
        x = x.fillna(med)
        sd = float(x.std(ddof=0))
        d[c] = x
        d["z_" + c] = (x - float(x.mean())) / sd if sd > 0 else 0.0

    Xc = d[["z_" + c for c in ADJ]].to_numpy(float)
    Xd = pd.get_dummies(d["sic2"], prefix="sic2", dtype=float)
    X = np.column_stack([Xc, Xd.to_numpy(float)])
    y = d["early_entry"].astype(int).to_numpy()
    ps = LogisticRegression(C=1.0, max_iter=10000, solver="lbfgs", random_state=SEED).fit(X, y).predict_proba(X)[:, 1]
    ps = np.clip(ps, 0.03, 0.97)
    d["propensity"] = ps
    d["overlap_weight"] = np.where(y == 1, 1 - ps, ps)
    d["overlap_weight"] /= d["overlap_weight"].mean()

    e = d[d.early_entry == 1]; l = d[d.early_entry == 0]
    weighted_smds = [smd(e[c], l[c], e.overlap_weight, l.overlap_weight) for c in ADJ]
    diag = {
        "ess": ess(d.overlap_weight),
        "max_abs_weighted_smd": float(max(abs(x) for x in weighted_smds)),
        "propensity_min": float(ps.min()),
        "propensity_max": float(ps.max()),
        "balance_ok_0_10": bool(max(abs(x) for x in weighted_smds) <= 0.10),
    }
    return d, diag

def extract(fit, param: str) -> dict:
    co = fit.coef()
    if param not in list(co.index):
        return {"status": "not_identified", "n": int(getattr(fit, "_N", 0)), "dropped": list(getattr(fit, "_collin_vars", []))}
    return {
        "status": "identified",
        "n": int(getattr(fit, "_N", 0)),
        "estimate": float(fit.coef().loc[param]),
        "se": float(fit.se().loc[param]),
        "p": float(fit.pvalue().loc[param]),
        "dropped": list(getattr(fit, "_collin_vars", [])),
    }

def fit_model(formula: str, param: str, d: pd.DataFrame, weighted=True, crv3=False) -> dict:
    kw = {"data": d, "fixef_rm": "singleton", "collin_tol": 1e-9}
    if weighted:
        kw.update({"weights": "overlap_weight", "weights_type": "aweights"})
    out = {}
    for name, vcov in [
        ("topic_crv1", {"CRV1": "topic_id"}),
        ("two_way_crv1", {"CRV1": "topic_id + company_id"}),
    ] + ([ ("topic_crv3", {"CRV3": "topic_id"}) ] if crv3 else []):
        try:
            out[name] = extract(pf.feols(formula, vcov=vcov, **kw), param)
        except Exception as exc:
            out[name] = {"status": "failed", "error": f"{type(exc).__name__}: {exc}"}
    return out

def supported_subset(d: pd.DataFrame, outcome: str, min_n=50, min_topics=15) -> tuple[pd.DataFrame, dict]:
    x = d[d[outcome].notna()].copy()
    if x.empty:
        return x, {"n": 0, "topics": 0, "support_ok": False}
    s = x.groupby("topic_id")["early_entry"].agg(["min", "max"])
    valid = s[(s["min"] == 0) & (s["max"] == 1)].index
    x = x[x.topic_id.isin(valid)].copy()
    return x, {"n": int(len(x)), "topics": int(x.topic_id.nunique()), "support_ok": bool(len(x) >= min_n and x.topic_id.nunique() >= min_topics)}

