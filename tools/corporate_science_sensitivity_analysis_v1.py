for g in passing:
    spec = str(g["emergence_spec"])
    w = int(g["early_window"])
    tbl = f"p_{spec}_w{w}"
    d, balance = prepare_df(tbl)
    key = f"{spec}_w{w}"

    # Same final primary estimator family as inference-hardened checkpoint.
    h1_3 = fit_model(f"y_h1_3 ~ early_entry + {OUTCOME_COMMON} | {FE3}", "early_entry", d, weighted=True)
    h2_3 = fit_model(f"y_h2_3 ~ early_entry + {OUTCOME_COMMON} | {FE3}", "early_entry", d, weighted=True)
